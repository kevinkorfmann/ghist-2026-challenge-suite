"""Recover raw paired reads from synthetic BAMs and realign using BWA-MEM."""
from __future__ import annotations

import shutil
from pathlib import Path
import subprocess

import pysam

from .pipeline import sha256, write_json


def remap_synthetic_bams(source: Path, output: Path, bwa: Path, threads: int = 4) -> dict:
    """Use synthetic reads; preserve the original truth-aligned BAMs separately."""
    if output.exists():
        raise FileExistsError(output)
    output.mkdir(parents=True)
    source = source.resolve()
    reference = output / 'reference.fasta'
    shutil.copy2(source / 'reference.fasta', reference)
    shutil.copy2(source / 'reference.fasta.fai', Path(str(reference) + '.fai'))
    shutil.copy2(source / 'popfile.txt', output / 'popfile.txt')
    protocol = {'method': 'bwa_mem_0.7.19', 'source_simulation_sha256': sha256(source / 'simulation.json'),
                'source_sha256': sha256(Path(__file__)), 'bwa_sha256': sha256(bwa), 'commands': [], 'bams': []}
    command = [str(bwa), 'index', str(reference)]
    protocol['commands'].append(command)
    write_json(output / 'remap_protocol.json', protocol)
    with (output / 'index.log').open('w') as log:
        subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, check=True)
    for line in (source / 'popfile.txt').read_text().splitlines():
        sample, _ = line.split()
        # Synthetic names are generated by this package, never user-provided paths.
        if not sample.startswith('synthetic_') or not sample.removeprefix('synthetic_').isdigit():
            raise ValueError('remapping harness accepts generated synthetic sample names only')
        named = output / f'{sample}.namesorted.bam'
        read1, read2 = output / f'{sample}.R1.fastq', output / f'{sample}.R2.fastq'
        pysam.sort('-n', '-o', str(named), str(source / f'{sample}.bam'))
        pysam.fastq('-1', str(read1), '-2', str(read2), '-0', '/dev/null', '-s', '/dev/null', '-n', str(named), catch_stdout=False)
        sam = output / f'{sample}.sam'
        command = [str(bwa), 'mem', '-t', str(threads), '-R', f'@RG\\tID:{sample}\\tSM:{sample}',
                   str(reference), str(read1), str(read2)]
        protocol['commands'].append(command)
        write_json(output / 'remap_protocol.json', protocol)
        with sam.open('w') as result, (output / f'{sample}.bwa.log').open('w') as log:
            subprocess.run(command, stdout=result, stderr=log, check=True)
        bam = output / f'{sample}.bam'
        pysam.sort('-o', str(bam), str(sam))
        pysam.index(str(bam))
        protocol['bams'].append({'sample': sample, 'sha256': sha256(bam),
                                 'source_bam_sha256': sha256(source / f'{sample}.bam'),
                                 'read1_sha256': sha256(read1), 'read2_sha256': sha256(read2)})
        # Remove only our disposable intermediates after indexed BAM completion.
        named.unlink()
        sam.unlink()
    write_json(output / 'remap_protocol.json', protocol)
    return protocol
